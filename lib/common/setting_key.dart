enum SettingKey {
  logoPosition,
  invoicePrefix,
  additionalInfo,
  thankYouNote,
  currency,
  upiId, // kept for backward-compat read only
  showUpiQr,
  upiIds, // JSON list of UpiEntry objects
  showGstFields, // whether to show GST/GSTIN fields
  fractionalQuantity, // whether to allow decimal quantities (e.g. 1.5 hrs)
  quantityLabel, // default label for the Qty column (e.g. "Words", "Hours")
  logoSize, // logo size on PDF: 'xsmall' | 'small' | 'medium' | 'large'
  businessType, // 'product' | 'service' | 'both'
  showQuantity, // whether to show quantity field (default true)
  bankAccounts, // JSON list of BankAccount objects
  showBankDetails, // whether to show bank details on PDF
  showPhone, // whether to show company phone on PDF (default true)
  showEmail, // whether to show company email on PDF (default true)
  showDiscount, // whether to show discount column on PDF (default true)
  showTypeTag, // whether to show product/service tag on invoice items (default true)
  lastUpdateCheck, // ISO timestamp of last GitHub release API call
  lastKnownLatestVersion, // latest version tag returned by last API call
  lastNotifiedVersion, // version for which the update dialog was last shown
  dateFormat, // date display pattern: 'dd/MM/yyyy' | 'MM/dd/yyyy' | 'dd MMM yyyy' | 'yyyy-MM-dd'
  showInvoiceFooterBranding, // show "Generated by Invoiso" in invoice PDF footer
  pdfThemeColor, // custom PDF accent/theme color as #RRGGBB
  dashboardLayout, // which dashboard layout to use: 'default' | 'classic' | 'simple'
  layoutBannerDismissed, // '1' once user dismisses the new-layouts discovery banner
  themeBannerDismissed, // '1' once user dismisses the dark-mode (beta) discovery banner
  signatureImage, // base64-encoded signature image
  signaturePosition, // 'left' | 'right'
  signatureSize, // signature size on PDF: 'small' | 'medium' | 'large'
  showPreviousBalance, // whether to show calculated Previous Balance Due on PDFs
  pageSize, // 'a4' | 'a6'
  showTotalQuantity, // show total quantity row in compact template footer
  supportBannerDismissed, // milestone at which support banner was last dismissed: '10' | '50' | '100'
  invoiceStartingNumber, // starting invoice number (only editable when invoice count is zero)
  invoiceLeadingZeros, // whether generated invoice numbers are zero-padded to 8 digits (default true; locked once invoices exist)
  defaultTaxRate, // default invoice tax rate percentage (e.g. '18')
  thermalWidthMargin, // chars trimmed off the thermal printer's textbook width to avoid edge clipping on real hardware; default '1'
  thermalItemLayout, // 'table' | 'detailed' — how items print on thermal receipts; default 'table'
  invoiceTemplate, // used by cloud edition's generic setSetting/getSetting path
  companyLogo, // used by cloud edition's generic setSetting/getSetting path
  installationId, // Unique identifier for this installation. Generated on first launch and persisted locally. Used for anonymous analytics and installation tracking.
  showAliasNameInPdf, // whether to print a product's local-language alias name instead of its actual name on PDFs (default false)
  showTaxButtonInInvoicePage,
  themeMode, // app theme: 'light' | 'dark' | 'system'
  watermarkImage, // base64-encoded watermark image shown behind invoice items table
  watermarkOpacity, // watermark opacity 0.0-1.0 as string; default '0.12'
  defaultInvoiceTitle, // GST document title preselected on new invoices: 'Tax Invoice' | 'Bill of Supply' | etc; null/empty = plain 'Invoice'
  allowDuplicateInvoiceItems, // whether the same product can be added twice to one invoice (default false)
  showCgstSgst, // whether to split tax into CGST/SGST (India, 50/50)
  defaultTaxMode, // 'global' | 'perItem' — default tax mode for new invoices
  showRoundOff, // whether to show round-off row + amount-in-words on PDFs (default false)
  showCompanyName, // whether to show company name on PDF (default true)
  showPan, // whether to show company PAN on PDF (default true)
  showFssai, // whether to show company FSSAI code on PDF (default true)
  showWebsite, // whether to show company website on PDF (default true)
  showAddress, // whether to show company address on PDF (default true)
  showLogo, // whether to show company logo on PDF (default true)
  productColumnsBannerDismissed, // '1' once user dismisses the product-columns discovery banner
  thermalCompanyNameSize, // 'xsmall' | 'small' | 'medium' | 'large' — company name font size on thermal receipts; default 'medium'
  lastUsedThermalPrinter, // JSON-encoded Printer of the last device successfully printed to, used to skip a full rescan on next open
  productColumnsConfig, // JSON ProductColumnsConfig — which optional product fields (and invoice extra cost) are visible/editable
  productListColumnsConfig, // JSON Map<String,bool> — which optional columns show in the product list table
  shortcutsBannerDismissed, // '1' once user dismisses the keyboard-shortcuts discovery banner
  createInvoiceLayout, // which create-invoice screen layout to use: 'v1' | 'v2'
  showCustomerStatsCards, // whether the stat cards row is shown on customer management v2 (default true)
  showProductStatsCards, // whether the stat cards row is shown on product management v2 (default true)
  hideInvoiceNumberByDefault, // whether the "Hide invoice number in PDF" toggle is on by default for new invoices (default false)
  showDescriptionInPdf, // whether to print a product's description as a full-width row under each invoice item on A4 PDFs (default false)
  descriptionNewLineInPdf, // when showDescriptionInPdf is on: print the description as a full-width row below the item instead of a line under the item name (default false)
  appLocale, // app UI language code, e.g. 'en' | 'ne' | 'bo' | 'fr' | 'es' | 'hi' | 'zh'; unset/empty = follow system locale
  onboardingCompleted, // '1' once the first-login onboarding wizard has been finished or skipped
  showCustomerBusinessNameInPdf, // whether to show the customer's business name on PDFs/thermal receipts (default true; only shown when non-empty)
  showCustomerAddressInPdf, // whether to show the customer's address on PDFs (default true; only shown when non-empty)
  showCustomerPhoneInPdf, // whether to show the customer's phone on PDFs/thermal receipts (default true; only shown when non-empty)
  showCustomerEmailInPdf, // whether to show the customer's email on PDFs (default true; only shown when non-empty)
  showCustomerGstinInPdf, // whether to show the customer's GSTIN/tax id on PDFs/thermal receipts (default true; only shown when non-empty and GST fields are on)
  showTimeInPdf, // whether the invoice creation time is appended to the date on PDFs/thermal receipts (default true)
  pdfTimeFormat, // time format used when showTimeInPdf is on: '24' (HH:mm) | '12' (h:mm a); default '24'
  showSlNoInPdf, // whether to print the Sl No column in the A4/Letter invoice items table (default true)
  pdfLandscape, // whether the Grid Classic invoice PDF renders in landscape orientation (default false)
  customFieldsEnabled, // whether the user-defined Custom Fields feature is on (default false)
  customFieldDefs, // JSON list of CustomFieldDef objects
}

