import 'dart:typed_data';

import 'package:intl/intl.dart';
import 'package:invoiso/common/constants.dart';
import 'package:invoiso/common/gst_utils.dart';
import 'package:invoiso/models/company_info.dart';
import 'package:invoiso/models/gstr3b_summary.dart';
import 'package:invoiso/services/pdf/pdf_font_service.dart';
import 'package:invoiso/services/pdf/pdf_report_header.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

/// GSTR-3B summary PDF (PurchaseGstReportsPlan.md P5) — a worksheet for
/// entering the return on the portal. English, like the other GST exports.
class Gstr3bPdfWriter {
  const Gstr3bPdfWriter._();

  static String _n(num v) => v.toStringAsFixed(2);

  static Future<Uint8List> build(
    Gstr3bSummary r, {
    required String periodLabel,
    required CompanyInfo? company,
    required String datePattern,
    bool showFooterBranding = true,
    pw.ThemeData? theme, // tests pass a font theme
  }) async {
    final doc = pw.Document(theme: theme ?? await PdfFontService.loadTheme());

    pw.Widget table(List<String> headers, List<List<String>> rows) =>
        pw.TableHelper.fromTextArray(
          headers: headers,
          data: rows,
          headerStyle: pw.TextStyle(
              fontWeight: pw.FontWeight.bold, fontSize: 8, color: PdfColors.white),
          cellStyle: const pw.TextStyle(fontSize: 8),
          headerDecoration:
              const pw.BoxDecoration(color: PdfReportHeader.accentColor),
          cellAlignments: {
            for (var c = 0; c < headers.length; c++)
              c: c == 0 ? pw.Alignment.centerLeft : pw.Alignment.centerRight,
          },
          columnWidths: {0: const pw.FlexColumnWidth(4)},
          cellHeight: 18,
          oddRowDecoration:
              const pw.BoxDecoration(color: PdfColor.fromInt(0xFFF8FAFC)),
        );
    pw.Widget heading(String text) => pw.Padding(
          padding: const pw.EdgeInsets.only(top: 12, bottom: 6),
          child: pw.Text(text,
              style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold)),
        );
    List<String> heads(String label, double? taxable, double igst, double cgst) =>
        [label, taxable == null ? '' : _n(taxable), _n(igst), _n(cgst), _n(cgst)];
    const taxHeader = ['Nature of supplies', 'Taxable value', 'IGST', 'CGST', 'SGST'];
    final notes = [
      if (!r.companyGstinValid) 'Company GSTIN is missing or invalid.',
      if (r.salesExcluded.isNotEmpty || r.salesWarnings.isNotEmpty)
        'Sales: ${r.salesExcluded.length} documents not included, '
            '${r.salesWarnings.length} warnings (see the GSTR-1 report).',
      if (r.purchaseWarnings.isNotEmpty)
        'Purchases: ${r.purchaseWarnings.length} warnings (see the purchase register).',
    ];

    doc.addPage(pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(24),
      header: (context) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          PdfReportHeader.build(
              company: company,
              title: 'GSTR-3B SUMMARY',
              generatedOn: DateFormat(datePattern).format(DateTime.now())),
          pw.Text('Return period: $periodLabel',
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700)),
          pw.SizedBox(height: 8),
        ],
      ),
      footer: (context) => pw.Container(
        alignment: pw.Alignment.centerRight,
        margin: const pw.EdgeInsets.only(top: 12),
        child: pw.Text(
          showFooterBranding
              ? 'Page ${context.pageNumber} of ${context.pagesCount}  -  Generated by Invoiso'
              : 'Page ${context.pageNumber} of ${context.pagesCount}',
          style: pw.TextStyle(
              fontSize: PdfLayout.footerBrandingFontSize, color: PdfColors.grey600),
        ),
      ),
      build: (context) => [
        for (final n in notes)
          pw.Text(n, style: const pw.TextStyle(fontSize: 9, color: PdfColors.orange800)),
        heading('3.1 Outward supplies and inward supplies liable to reverse charge'),
        table(taxHeader, [
          heads('(a) Outward taxable supplies (other than zero rated, nil rated and exempted)',
              r.outwardTaxable.taxable, r.outwardTaxable.tax.igst, r.outwardTaxable.tax.cgst),
          heads('(b) Outward taxable supplies (zero rated)', r.outwardZeroRated, 0, 0),
          heads('(c) Other outward supplies (nil rated, exempted)', r.outwardNilExempt, 0, 0),
          heads('(d) Inward supplies (liable to reverse charge)',
              r.inwardReverseCharge.taxable, r.inwardReverseCharge.tax.igst,
              r.inwardReverseCharge.tax.cgst),
          heads('(e) Non-GST outward supplies', r.outwardNonGst, 0, 0),
        ]),
        if (r.interStateUnregistered.isNotEmpty) ...[
          heading('3.2 Inter-state supplies to unregistered persons'),
          table(['Place of supply', 'Taxable value', 'IGST'], [
            for (final x in r.interStateUnregistered)
              [GstUtils.stateLabel(x.pos), _n(x.taxable), _n(x.igst)],
          ]),
        ],
        heading('4 Eligible ITC'),
        table(taxHeader, [
          heads('A(3) Inward supplies liable to reverse charge', null,
              r.itcReverseCharge.igst, r.itcReverseCharge.cgst),
          heads('A(5) All other ITC', null, r.itcOther.igst, r.itcOther.cgst),
          heads('C Net ITC available', null, r.itcNet.igst, r.itcNet.cgst),
          heads('Not claimable - no valid supplier GSTIN (information)', null,
              r.notClaimable.igst, r.notClaimable.cgst),
        ]),
        pw.Padding(
          padding: const pw.EdgeInsets.only(top: 4),
          child: pw.Text(
              'ITC assumes every bill from a registered supplier is eligible - '
              'check blocked credits (Sec 17(5)) before claiming.',
              style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600)),
        ),
        heading('5 Exempt, nil rated and non-GST inward supplies'),
        table(['Nature of supplies', 'Inter-state', 'Intra-state'], [
          ['Nil rated / exempt purchases (0% lines)',
            _n(r.inwardExemptInter), _n(r.inwardExemptIntra)],
        ]),
        heading('6.1 Payment of tax'),
        table(['Tax', 'Payable', 'Paid via ITC', 'Paid in cash', 'ITC carried forward'], [
          for (final (name, p) in [('IGST', r.igst), ('CGST', r.cgst), ('SGST', r.sgst)])
            [name, _n(p.payable), _n(p.paidByItc), _n(p.paidInCash), _n(p.itcLeft)],
        ]),
      ],
    ));
    return doc.save();
  }
}
