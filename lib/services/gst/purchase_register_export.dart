import 'package:pdf/widgets.dart' as pw;

/// Purchase register exports (PurchaseGstReportsPlan.md P2): CSV for the CA
/// to reconcile against GSTR-2B, and a printable PDF. English, like the other
/// report exports.
class PurchaseRegisterExport {
  const PurchaseRegisterExport._();

  static String _n(num v) => v.toStringAsFixed(2);
  static String _state(PurchaseGstRow r) =>
      r.supplierState == null ? '' : GstUtils.stateLabel(r.supplierState!);

  static String csv(List<PurchaseGstRow> rows, {required String datePattern}) {
    final date = DateFormat(datePattern);
    return buildQuotedCsv([
      ['Date', 'Bill No', 'Supplier', 'Supplier GSTIN', 'Supplier State',
        'Taxable Value', 'IGST', 'CGST', 'SGST', 'Total', 'ITC', 'Reverse Charge'],
      for (final r in rows)
        [
          date.format(r.date), r.billNumber, r.supplierName, r.supplierGstin,
          _state(r), _n(r.taxable), _n(r.igst), _n(r.cgst), _n(r.sgst),
          _n(r.total), r.itcEligible ? 'Y' : 'N', r.reverseCharge ? 'Y' : 'N',
        ],
    ]);
  }

  static Future<Uint8List> pdf(
    PurchaseGstReport r, {
    required String periodLabel,
    required CompanyInfo? company,
    required String datePattern,
    bool showFooterBranding = true,
    pw.ThemeData? theme, // tests pass a font theme
  }) async {
    final doc = pw.Document(theme: theme ?? await PdfFontService.loadTheme());
    final date = DateFormat(datePattern);
    String rate(double v) => '${v.toStringAsFixed(v % 1 == 0 ? 0 : 2)}%';
    double sum(double Function(PurchaseGstRow) f) =>
        r.rows.fold(0.0, (a, x) => a + f(x));

    pw.Widget table(List<String> headers, List<List<String>> rows,
            {required int firstNumber}) =>
        pw.TableHelper.fromTextArray(
          headers: headers,
          data: rows,
          headerStyle: pw.TextStyle(
              fontWeight: pw.FontWeight.bold, fontSize: 8, color: PdfColors.white),
          cellStyle: const pw.TextStyle(fontSize: 8),
          headerDecoration:
              const pw.BoxDecoration(color: PdfReportHeader.accentColor),
          cellAlignments: {
            for (var c = 0; c < headers.length; c++)
              c: c >= firstNumber
                  ? pw.Alignment.centerRight
                  : pw.Alignment.centerLeft,
          },
          cellHeight: 18,
          oddRowDecoration:
              const pw.BoxDecoration(color: PdfColor.fromInt(0xFFF8FAFC)),
        );
    pw.Widget heading(String text) => pw.Padding(
          padding: const pw.EdgeInsets.only(top: 12, bottom: 6),
          child: pw.Text(text,
              style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold)),
        );

    doc.addPage(pw.MultiPage(
      pageFormat: PdfPageFormat.a4.landscape,
      margin: const pw.EdgeInsets.all(24),
      header: (context) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          PdfReportHeader.build(
              company: company,
              title: 'PURCHASE REGISTER',
              generatedOn: date.format(DateTime.now())),
          pw.Text('Period: $periodLabel',
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700)),
          pw.Text(
              'ITC = Y: reverse charge, or supplier with a valid GSTIN. Check '
              'blocked credits (Sec 17(5)) before claiming.',
              style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600)),
          pw.SizedBox(height: 8),
        ],
      ),
      footer: (context) => pw.Container(
        alignment: pw.Alignment.centerRight,
        margin: const pw.EdgeInsets.only(top: 12),
        child: pw.Text(
          showFooterBranding
              ? 'Page ${context.pageNumber} of ${context.pagesCount}  -  Generated by Invoiso'
              : 'Page ${context.pageNumber} of ${context.pagesCount}',
          style: pw.TextStyle(
              fontSize: PdfLayout.footerBrandingFontSize, color: PdfColors.grey600),
        ),
      ),
      build: (context) => [
        heading('By rate'),
        table(
          ['Rate', 'Taxable', 'IGST', 'CGST', 'SGST'],
          [
            for (final b in r.byRate)
              [rate(b.rate), _n(b.taxable), _n(b.igst), _n(b.cgst), _n(b.sgst)],
          ],
          firstNumber: 1,
        ),
        heading('Bills (${r.rows.length})'),
        table(
          ['Date', 'Bill No', 'Supplier', 'GSTIN', 'State', 'Taxable', 'IGST',
            'CGST', 'SGST', 'Total', 'ITC', 'RCM'],
          [
            for (final x in r.rows)
              [
                date.format(x.date), x.billNumber, x.supplierName,
                x.supplierGstin, _state(x), _n(x.taxable), _n(x.igst), _n(x.cgst),
                _n(x.sgst), _n(x.total), x.itcEligible ? 'Y' : 'N',
                x.reverseCharge ? 'Y' : 'N',
              ],
            [
              'Total', '', '', '', '', _n(sum((x) => x.taxable)),
              _n(sum((x) => x.igst)), _n(sum((x) => x.cgst)),
              _n(sum((x) => x.sgst)), _n(sum((x) => x.total)), '', '',
            ],
          ],
          firstNumber: 5,
        ),
      ],
    ));
    return doc.save();
  }
}
