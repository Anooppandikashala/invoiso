import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import 'formatters.dart';
import 'template_options.dart';

part 'blocks_v2.dart';

/// Renders a user-imported block layout document.
///
/// The document shape is `{ page, theme, layout: [ ...blocks ] }`, where each
/// block has a `type` such as `header`, `divider`, `twoColumn`, `table`,
/// `summary`, `box`, `signature` or `footer`. Values may contain
/// `{{placeholders}}` which are resolved against [data] (see README for the
/// data contract).
pw.MultiPage buildBlockLayoutPage({
  required Map<String, dynamic> document,
  required Map<String, dynamic> data,
  TemplateOptions options = const TemplateOptions(),
  TemplateAssets assets = const TemplateAssets(),
  PdfPageFormat fallbackPageFormat = PdfPageFormat.a4,
}) {
  final renderer = _BlockLayoutRenderer(
    document: document,
    data: data,
    options: options,
    assets: assets,
    fallbackPageFormat: fallbackPageFormat,
  );

  // Space between top-level blocks; v2 layouts may set their own (0 for
  // tightly framed grids).
  final gap = renderer.isV2
      ? _BlockLayoutRenderer._double(document['gap'], fallback: 12)
      : 12.0;
  return pw.MultiPage(
    pageTheme: renderer.pageTheme,
    header: renderer.isV2
        ? (context) =>
            renderer.pageSection('pageHeader', context) ?? pw.SizedBox()
        : null,
    footer: (context) {
      // App-owned branding follows the app setting, never the layout JSON.
      final branding = pw.Container(
        alignment: pw.Alignment.centerRight,
        margin: const pw.EdgeInsets.only(top: 12),
        child: pw.Text(
          options.showFooterBranding
              ? "Page ${context.pageNumber} of ${context.pagesCount}  -  Generated by Invoiso"
              : "Page ${context.pageNumber} of ${context.pagesCount}",
          style: pw.TextStyle(fontSize: options.footerFontSize * options.fontScale, color: PdfColors.grey600),
        ),
      );
      final layoutFooter =
          renderer.isV2 ? renderer.pageSection('pageFooter', context) : null;
      return layoutFooter == null
          ? branding
          : pw.Column(children: [layoutFooter, branding]);
    },
    build: (context) {
      final widgets = <pw.Widget>[];
      var renderedBlocks = 0;
      for (final block in renderer.blocks) {
        final parts = renderer.pageWidgets(block);
        if (parts.isEmpty) continue;
        widgets.addAll(parts);
        renderedBlocks++;
        if (gap > 0 && block['type'] != 'divider' && block['type'] != 'footer') {
          widgets.add(pw.SizedBox(height: gap));
        }
      }
      // A layout can be imported with block names this renderer does not know.
      // Never emit an empty page in that case: render the standard invoice
      // structure using the imported document's own page + theme. This is not
      // the built-in Classic template, so the inserted layout's colours and
      // paper size are still the ones the user sees.
      if (renderedBlocks == 0) {
        widgets.addAll(renderer.buildFallbackBlocks());
      }
      return widgets;
    },
  );
}

/// The paper size a layout document prints on ([fallback] when it sets none).
PdfPageFormat templatePageFormat(
    Map<String, dynamic> document, PdfPageFormat fallback) {
  final page =
      _BlockLayoutRenderer._asMap(document['page'] ?? document['paper']);
  return _BlockLayoutRenderer._pageFormat(
      page, fallback, _BlockLayoutRenderer._pageUnit(page));
}

class _BlockLayoutRenderer {
  _BlockLayoutRenderer({
    required this.document,
    required this.data,
    required this.options,
    required this.assets,
    required PdfPageFormat fallbackPageFormat,
  })  : blocks = _blocksOf(document),
        pageTheme = _buildPageTheme(document, fallbackPageFormat,
            options: options,
            watermark: assets.watermark,
            declined: _asMap(data['invoice'])['status'] == 'declined');

  final Map<String, dynamic> document;
  final Map<String, dynamic> data;
  final TemplateOptions options;
  final TemplateAssets assets;

  /// `"engine": 2` layouts get the v2 building blocks (blocks_v2.dart).
  late final bool isV2 = ((document['engine'] as num?)?.toInt() ?? 1) >= 2;
  late final Map<String, dynamic> _styles = _asMap(document['styles']);

  /// Set while a v2 page header/footer is built, for {{page}} / {{pages}}.
  pw.Context? _pageContext;

  /// Current list item while a v2 table / repeat renders (`{{row.*}}`).
  Map<String, dynamic>? _row;

  final List<Map<String, dynamic>> blocks;
  final pw.PageTheme pageTheme;

  // One image object per document, so repeated logo/signature blocks embed
  // the bytes once instead of once per block.
  late final pw.MemoryImage? _logoImage =
      assets.logo == null ? null : pw.MemoryImage(assets.logo!);
  late final pw.MemoryImage? _signatureImage =
      assets.signature == null ? null : pw.MemoryImage(assets.signature!);

  // Data sections (see README "Data contract").
  late final Map<String, dynamic> _invoice = _asMap(data['invoice']);
  late final Map<String, dynamic> _customer = _asMap(data['customer']);
  late final Map<String, dynamic> _company = _asMap(data['company']);
  late final Map<String, dynamic> _bank = _asMap(data['bank']);
  late final Map<String, dynamic> _totals = _asMap(data['totals']);
  late final List<Map<String, dynamic>> _items = [
    for (final item in (data['items'] is List ? data['items'] as List : const []))
      _asMap(item),
  ];

  /// Font size × the PDF text-size settings: the section size for company
  /// name / document title / table header / table items / totals, else the
  /// overall size.
  double _fs(double size, [String? role]) =>
      size *
      switch (role) {
        'companyName' => options.companyNameScale,
        'docTitle' => options.docTitleScale,
        'tableHeader' => options.tableHeaderScale,
        'tableItems' => options.tableItemsScale,
        'totals' => options.totalsScale,
        _ => options.fontScale,
      };

  static String _s(Map<String, dynamic> map, String key) =>
      map[key]?.toString() ?? '';
  static double _n(Map<String, dynamic> map, String key) =>
      (map[key] as num?)?.toDouble() ?? 0;
  String _date(dynamic iso, {bool withTime = false}) {
    final date = iso == null ? null : DateTime.tryParse(iso.toString());
    return date == null
        ? ''
        : formatDate(date, options.datePattern,
            withTime: withTime && options.showTime,
            timeFormat: options.timeFormat);
  }

  late final Map<String, dynamic> _theme =
      _asMap(document['theme'] ?? document['colors']);
  late final PdfColor primary = _color(
      _theme['primary'] ??
          _theme['primaryColor'] ??
          _theme['color'] ??
          _theme['accent'],
      fallback: options.themeColor ?? PdfColor.fromHex('#2563EB'));
  late final PdfColor textColor = _color(
      _theme['text'] ?? _theme['textColor'] ?? _theme['foreground'],
      fallback: PdfColor.fromHex('#111827'));
  late final PdfColor mutedColor = _color(
      _theme['muted'] ?? _theme['mutedColor'] ?? _theme['secondaryText'],
      fallback: PdfColor.fromHex('#6B7280'));
  late final PdfColor borderColor = _color(
      _theme['border'] ?? _theme['borderColor'] ?? _theme['divider'],
      fallback: PdfColor.fromHex('#E5E7EB'));

  String _typeOf(Map<String, dynamic> block) =>
      (block['type'] ?? _inferBlockType(block))
          ?.toString()
          .trim()
          .toLowerCase() ??
      '';

  static const _tableTypes = {
    'table',
    'items',
    'lineitems',
    'line_items',
    'invoiceitems',
    'invoice_items',
    'products',
  };

  /// Widgets for one top-level block. An items table is returned as its own
  /// page child (not wrapped in a Column) so MultiPage can split long item
  /// lists across pages.
  List<pw.Widget> pageWidgets(Map<String, dynamic> block) {
    if (_tableTypes.contains(_typeOf(block))) {
      if (!isV2) return _tableParts(block);
      return _truthy(block['if']) ? tableV2Parts(block) : const [];
    }
    final widget = buildBlock(block);
    return widget == null ? const [] : [widget];
  }

  pw.Widget? buildBlock(Map<String, dynamic> block) {
    final type = _typeOf(block);
    if (isV2) {
      if (!_truthy(block['if'])) return null;
      if (_BlocksV2.types.contains(type)) return buildV2(type, block);
      if (_tableTypes.contains(type)) {
        final parts = tableV2Parts(block);
        return parts.isEmpty ? null : pw.Column(children: parts);
      }
    }
    switch (type) {
      case 'header':
        return _header(block);
      case 'divider':
        return pw.Divider(color: borderColor, thickness: 0.8, height: 8);
      case 'twocolumn':
      case 'two_column':
        return _twoColumn(block);
      case 'table':
      case 'items':
      case 'lineitems':
      case 'line_items':
      case 'invoiceitems':
      case 'invoice_items':
      case 'products':
        return _table(block);
      case 'summary':
      case 'totals':
        return _summary(block);
      case 'customer':
      case 'billto':
      case 'bill_to':
      case 'billing':
      case 'customerinfo':
      case 'customer_info':
        return _customerBlock(block);
      case 'company':
      case 'seller':
      case 'from':
      case 'companyinfo':
      case 'company_info':
        return _companyBlock(block);
      case 'invoicedetails':
      case 'invoice_details':
      case 'invoicemeta':
      case 'invoice_meta':
      case 'metadata':
      case 'details':
        return _invoiceDetailsBlock(block);
      case 'bank':
      case 'bankdetails':
      case 'bank_details':
      case 'payment':
      case 'paymentdetails':
      case 'payment_details':
        return _bankBlock(block);
      case 'box':
      case 'note':
      case 'notes':
      case 'terms':
        return _box(block);
      case 'signature':
        return _signature(block);
      case 'footer':
        return _footer(block);
      case 'spacer':
        final height = _double(block['height'], fallback: 12);
        return pw.SizedBox(height: height.clamp(0.0, 400.0));
      case 'text':
      case 'paragraph':
        return _textBlock(block);
      case 'row':
      case 'columns':
      case 'column':
      case 'container':
      case 'section':
      case 'group':
        return _containerBlock(block);
      case 'image':
      case 'logo':
        return _imageBlock(block);
      default:
        // Unknown custom block names still render their readable content
        // instead of being silently dropped. Nested containers are rendered
        // recursively before falling back to plain text collection.
        return _containerBlock(block) ?? _genericBlock(block);
    }
  }

  String? _inferBlockType(Map<String, dynamic> block) {
    final keys = block.keys.map((key) => key.toLowerCase()).toSet();
    if (keys.contains('columns')) return 'table';
    if (keys.contains('rows')) return 'summary';
    if (keys.contains('branding') || keys.contains('note')) return 'footer';
    if (keys.contains('children') ||
        keys.contains('blocks') ||
        keys.contains('sections') ||
        keys.contains('elements')) {
      return 'container';
    }
    if (keys.contains('customer') || keys.contains('billto')) {
      return 'customer';
    }
    if (keys.contains('company') || keys.contains('seller')) {
      return 'company';
    }
    if (keys.contains('items') || keys.contains('lineitems')) return 'table';
    if (keys.contains('totals')) return 'summary';
    if (keys.contains('bank') || keys.contains('payment')) return 'bank';
    if (keys.contains('left') || keys.contains('right')) {
      if (keys.contains('title') ||
          block['right'] is Map &&
              (_asMap(block['right'])['title'] != null ||
                  _asMap(block['right'])['invoiceNo'] != null)) {
        return 'header';
      }
      return 'twoColumn';
    }
    if (keys.contains('content') || keys.contains('text')) return 'text';
    if (keys.contains('label') && keys.contains('signature')) {
      return 'signature';
    }
    if (keys.contains('title')) return 'box';
    if (keys.contains('height')) return 'spacer';
    return null;
  }

  pw.Widget? _genericBlock(Map<String, dynamic> block) {
    final title = _resolve(block['title']?.toString() ?? '');
    final explicitContent = _resolve(
      block['content']?.toString() ??
          block['text']?.toString() ??
          block['value']?.toString() ??
          '',
    );
    final lines = <String>[];
    if (explicitContent.trim().isNotEmpty) {
      lines.add(explicitContent);
    } else {
      lines.addAll(_collectTextValues(block, skip: const {'title'}));
    }
    if (title.isEmpty && lines.isEmpty) return null;
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.all(8),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: borderColor, width: 0.6),
        borderRadius: const pw.BorderRadius.all(pw.Radius.circular(3)),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          if (title.isNotEmpty) ...[
            pw.Text(title,
                style: pw.TextStyle(
                    fontSize: _fs(10),
                    fontWeight: pw.FontWeight.bold,
                    color: textColor)),
            pw.SizedBox(height: 4),
          ],
          for (final line in lines)
            pw.Padding(
              padding: const pw.EdgeInsets.only(bottom: 2),
              child: pw.Text(line,
                  style: pw.TextStyle(fontSize: _fs(9.5), color: textColor)),
            ),
        ],
      ),
    );
  }

  /// Renders nested/unknown layout containers instead of dropping them.
  pw.Widget? _containerBlock(Map<String, dynamic> block) {
    final children = _childBlocks(block);
    if (children.isEmpty) return null;
    final widgets = <pw.Widget>[];
    for (final child in children) {
      final widget = buildBlock(child);
      if (widget == null) continue;
      if (widgets.isNotEmpty) widgets.add(pw.SizedBox(height: 8));
      widgets.add(widget);
    }
    if (widgets.isEmpty) return null;
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: widgets,
    );
  }

  List<Map<String, dynamic>> _childBlocks(Map<String, dynamic> block) {
    for (final key in const [
      'children',
      'blocks',
      'sections',
      'elements',
      'layout',
      'items',
    ]) {
      final raw = block[key];
      if (raw is List) {
        final result = <Map<String, dynamic>>[];
        for (final entry in raw) {
          final map = _asMap(entry);
          if (map.isNotEmpty &&
              (map.containsKey('type') || map.length > 1)) {
            result.add(map);
          }
        }
        if (result.isNotEmpty) return result;
      }
      final nested = _asMap(raw);
      if (nested.isNotEmpty) {
        final child = _childBlocks(nested);
        if (child.isNotEmpty) return child;
      }
    }
    final left = _asMap(block['left']);
    final right = _asMap(block['right']);
    if (left.isNotEmpty || right.isNotEmpty) {
      return [
        if (left.isNotEmpty) left,
        if (right.isNotEmpty) right,
      ];
    }
    return const [];
  }

  List<String> _collectTextValues(
    Map<String, dynamic> block, {
    Set<String> skip = const {},
  }) {
    final result = <String>[];
    for (final entry in block.entries) {
      final key = entry.key.toLowerCase();
      if (key == 'type' ||
          key == 'align' ||
          key == 'color' ||
          key == 'background' ||
          key == 'border' ||
          key == 'width' ||
          key == 'height' ||
          key == 'bold' ||
          key == 'highlight' ||
          skip.contains(key)) {
        continue;
      }
      final value = entry.value;
      if (value is String && value.trim().isNotEmpty) {
        final text = _resolve(value).trim();
        if (text.isNotEmpty) result.add(text);
      } else if (value is num) {
        result.add(value.toString());
      } else if (value is Map) {
        final map = _asMap(value);
        result.addAll(_collectTextValues(map));
      } else if (value is List) {
        for (final child in value) {
          final map = _asMap(child);
          if (map.isNotEmpty) {
            result.addAll(_collectTextValues(map));
          } else if (child is String && child.trim().isNotEmpty) {
            final text = _resolve(child).trim();
            if (text.isNotEmpty) result.add(text);
          }
        }
      }
    }
    return result;
  }

  List<String> _fieldStrings(dynamic value) {
    final result = <String>[];
    if (value is String && value.trim().isNotEmpty) {
      result.add(_resolveLine(value));
    } else if (value is List) {
      for (final entry in value) {
        if (entry is String && entry.trim().isNotEmpty) {
          result.add(_resolveLine(entry));
        } else {
          final map = _asMap(entry);
          if (map.isEmpty) continue;
          final text = map['text'] ??
              map['value'] ??
              map['label'] ??
              map['content'] ??
              map['line'];
          if (text != null && text.toString().trim().isNotEmpty) {
            result.add(_resolveLine(text.toString()));
          }
        }
      }
    }
    result.removeWhere((line) => line.trim().isEmpty);
    return result;
  }

  pw.Widget? _infoBlock(
    Map<String, dynamic> block, {
    required String fallbackTitle,
    required List<String> fallbackFields,
  }) {
    final title =
        _resolve(block['title']?.toString() ?? block['label']?.toString() ?? '');
    final fields = _fieldStrings(
      block['fields'] ??
          block['lines'] ??
          block['values'] ??
          block['content'] ??
          block['text'],
    );
    final effectiveFields = fields.isEmpty ? fallbackFields : fields;
    if (effectiveFields.isEmpty) return null;
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text((title.isEmpty ? fallbackTitle : title).toUpperCase(),
            style: pw.TextStyle(
                fontSize: _fs(8.5),
                fontWeight: pw.FontWeight.bold,
                letterSpacing: 0.6,
                color: primary)),
        pw.SizedBox(height: 5),
        for (final field in effectiveFields)
          pw.Padding(
            padding: const pw.EdgeInsets.only(bottom: 2.5),
            child: pw.Text(field,
                style: pw.TextStyle(fontSize: _fs(9.5), color: textColor)),
          ),
      ],
    );
  }

  pw.Widget? _customerBlock(Map<String, dynamic> block) {
    return _infoBlock(
      block,
      fallbackTitle: 'Bill To',
      fallbackFields: [
        for (final key in const ['name', 'businessName', 'address', 'phone', 'email'])
          if (_s(_customer, key).trim().isNotEmpty) _s(_customer, key),
        if (options.showGst && _s(_customer, 'gstin').trim().isNotEmpty)
          _s(_customer, 'gstin'),
      ],
    );
  }

  pw.Widget? _companyBlock(Map<String, dynamic> block) {
    return _infoBlock(
      block,
      fallbackTitle: 'From',
      fallbackFields: [
        for (final key in const ['name', 'address', 'phone', 'email', 'website'])
          if (_s(_company, key).trim().isNotEmpty) _s(_company, key),
        if (options.showGst && _s(_company, 'gstin').trim().isNotEmpty)
          _s(_company, 'gstin'),
      ],
    );
  }

  pw.Widget? _invoiceDetailsBlock(Map<String, dynamic> block) {
    final number = _s(_invoice, 'number');
    return _infoBlock(
      block,
      fallbackTitle: 'Invoice Details',
      fallbackFields: [
        if (number.isNotEmpty) 'Invoice No: $number',
        'Date: ${_date(_invoice['date'])}',
        if (_invoice['dueDate'] != null)
          'Due Date: ${_date(_invoice['dueDate'])}',
        if (_s(_invoice, 'status').isNotEmpty) 'Status: ${_s(_invoice, 'status')}',
      ],
    );
  }

  pw.Widget? _bankBlock(Map<String, dynamic> block) {
    return _infoBlock(
      block,
      fallbackTitle: 'Payment Details',
      fallbackFields: [
        if (_s(_bank, 'name').trim().isNotEmpty) 'Bank: ${_s(_bank, 'name')}',
        if (_s(_bank, 'account').trim().isNotEmpty)
          'Account: ${_s(_bank, 'account')}',
        if (_s(_bank, 'ifsc').trim().isNotEmpty) 'IFSC: ${_s(_bank, 'ifsc')}',
        if (_s(_bank, 'iban').trim().isNotEmpty) 'IBAN: ${_s(_bank, 'iban')}',
        if (_s(_bank, 'upi').trim().isNotEmpty) 'UPI: ${_s(_bank, 'upi')}',
      ],
    );
  }

  pw.Widget? _imageBlock(Map<String, dynamic> block) {
    final source = (block['source'] ?? block['src'] ?? block['image'] ?? '')
        .toString()
        .toLowerCase();
    final wantsSignature = source.contains('signature');
    // An explicit logo block never falls back to the signature (no logo →
    // nothing); only a source-less image keeps the old logo-else-signature.
    final image = wantsSignature
        ? _signatureImage
        : source.contains('logo')
            ? _logoImage
            : (_logoImage ?? _signatureImage);
    if (image == null) return null;
    final height = _double(block['height'],
        fallback: wantsSignature ? 40 : (options.logoSize ?? 42));
    return pw.Align(
      alignment: _alignment(block['align'] ?? 'left'),
      child: pw.Image(
        image,
        height: height.clamp(12.0, 120.0),
        fit: pw.BoxFit.contain,
      ),
    );
  }

  /// The invoice body used when a layout contains only block names this
  /// renderer does not recognise. It intentionally uses the imported
  /// document's theme/page rather than the built-in Classic template.
  List<pw.Widget> buildFallbackBlocks() {
    final defaults = <Map<String, dynamic>>[
      {
        'type': 'header',
        'left': {
          'companyName': '{{company.name}}',
          'tagline': '{{company.address}}',
        },
        'right': {
          'title': '{{invoice.title}}',
          'invoiceNo': '{{invoice.number}}',
          'date': '{{invoice.date}}',
        },
      },
      {
        'type': 'twoColumn',
        'left': {
          'title': 'Bill To',
          'fields': [
            '{{customer.name}}',
            '{{customer.address}}',
            '{{customer.phone}}',
            '{{customer.email}}',
            '{{customer.gstin}}',
          ],
        },
        'right': {
          'title': 'Invoice Details',
          'fields': [
            '{{invoice.number}}',
            '{{invoice.date}}',
            '{{invoice.status}}',
          ],
        },
      },
      {'type': 'table'},
      {
        'type': 'summary',
        'rows': [
          {'label': 'Subtotal', 'value': '{{subtotal}}'},
          {'label': 'Tax', 'value': '{{tax}}'},
          {'label': 'Total', 'value': '{{total}}', 'highlight': true},
        ],
      },
      {'type': 'footer'},
    ];
    final widgets = <pw.Widget>[];
    for (final block in defaults) {
      final parts = pageWidgets(block);
      if (parts.isEmpty) continue;
      if (widgets.isNotEmpty) widgets.add(pw.SizedBox(height: 12));
      widgets.addAll(parts);
    }
    return widgets;
  }

